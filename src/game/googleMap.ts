export function buildGoogleMap(
  celdas: Celda[][],
  ancho: number,
  alto: number,
  colores: Record<string, string>,
  teletransportes: Record<string, Posicion>,
): void {
  buildBorderWalls(celdas, ancho, alto);
  buildFromTramos(celdas, colores, TRAMOS_POR_FILA, NOMBRES_COLORES);

  buildTeleportPair(
    celdas,
    teletransportes,
    { x: 0, y: 8 },
    { x: ancho - 1, y: 8 },
  );
}
